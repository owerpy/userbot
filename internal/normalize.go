// NormalizeVehicle приводит тип кузова к коду приложения
// (open/closed/refrigerator/tank/flatbed). Не распознали — пусто.
func NormalizeVehicle(raw string) string {
	x := regionKey(raw)
	if x == "" {
		return ""
	}
	if v, ok := vehicleAliases[x]; ok {
		return v
	}
	// вхождение: «tentli fura», «реф 20 тонн»
	for k, v := range vehicleAliases {
		if strings.Contains(x, k) {
			return v
		}
	}
	return ""
}

