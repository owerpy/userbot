// служебные слова, которые не влияют на распознавание региона
var regionNoise = []string{
	"viloyati", "viloyat", "shahri", "shahar", "tumani",
	"вилояти", "шахри", "область", "областа", "обл", "область.",
	"region", "oblast", "г.", "гор.", "город",
}

// regionKey приводит написание к сравнимому виду: нижний регистр,
// без апострофов/дефисов/пробелов и служебных слов.
func regionKey(s string) string {
	x := strings.ToLower(strings.TrimSpace(s))
	// узбекская латиница: o‘/g‘ и апострофы
	rep := strings.NewReplacer(
		"o‘", "o", "g‘", "g", "o'", "o", "g'", "g",
		"ʻ", "", "'", "", "‘", "", "’", "`", "`", "",
		"ў", "у", "қ", "к", "ғ", "г", "ҳ", "х",
	)
	x = rep.Replace(x)
	for _, w := range regionNoise {
		x = strings.ReplaceAll(x, w, " ")
	}
	// убрать всё, кроме букв и цифр
	var b strings.Builder
	for _, r := range x {
		if r == ' ' || r == '-' || r == '.' || r == ',' {
			continue
		}
		b.WriteRune(r)
	}
	return b.String()
}

// NormalizeRegion приводит регион к справочнику приложения.
// Возвращает канон и код страны; если не распознали — исходную строку.
func NormalizeRegion(raw string) (region string, country string) {
	raw = strings.TrimSpace(raw)
	if raw == "" {
		return "", ""
	}
	if c, ok := regionAliases[regionKey(raw)]; ok {
		return c.Region, c.Country
	}
	// иногда приходит «Ташкент — Самарканд» одной строкой: берём первое слово
	if i := strings.IndexAny(raw, "-—–,/"); i > 0 {
		if c, ok := regionAliases[regionKey(raw[:i])]; ok {
			return c.Region, c.Country
		}
	}
	return raw, ""
}

